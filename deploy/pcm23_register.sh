#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
# PCM-23 — register the 3 new RAG providers in rag-registry, add them to the
# portal consumer (rag.ai.ismc.ir), and verify end-to-end through rag-gateway
# with a temporary verification consumer.
#   - additive env lines only (no edit of existing lines)
#   - `docker compose up -d` recreate of registry+gateway (env changed)
#     — NO `down`, NO volume removal; DB persists (bind mount)
#   - admin token verified identical in file/container/gateway before recreate
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail
DRAG=/home/saber/dedicated-rag
REG=/home/saber/dedicated-rag-registry
GW=/home/saber/dedicated-rag-gateway
TS=$(date +%Y%m%d-%H%M%S)
fail() { echo "!!! FAILED: $1"; exit 1; }

echo "=== 1. admin token (container env; equals file+gateway tokens) ==="
TOK=$(docker inspect rag-registry --format '{{.Config.Env}}' | tr ' ' '\n' | grep '^REGISTRY_ADMIN_TOKEN=' | cut -d= -f2-)
[ -n "$TOK" ] || fail "no REGISTRY_ADMIN_TOKEN"
printf '%s' "$TOK" > /tmp/pcm23-regtok
chmod 600 /tmp/pcm23-regtok
RAUTH="Authorization: Bearer $TOK"
reg() { curl -s -m 15 -H "$RAUTH" "$@"; }

echo "=== 2. provider service tokens (generated by pcm23_setup_rags.sh) ==="
PT_MIZAN3=$(grep '^DRAG_SERVICE_TOKEN=' "$DRAG/env/mizan3.env" | cut -d= -f2-)
PT_ALGHADR=$(grep '^DRAG_SERVICE_TOKEN=' "$DRAG/env/alghadir.env" | cut -d= -f2-)
PT_MANLA=$(grep '^DRAG_SERVICE_TOKEN=' "$DRAG/env/manla.env" | cut -d= -f2-)
[ -n "$PT_MIZAN3" ] && [ -n "$PT_ALGHADR" ] && [ -n "$PT_MANLA" ] || fail "provider tokens missing"

echo "=== 3. additive env lines (registry + gateway) ==="
add_env_line() { # file KEY VALUE
  local f=$1 k=$2 v=$3
  if grep -q "^$k=" "$f"; then echo "exists $k in ${f##*/}"
  else printf '%s=%s\n' "$k" "$v" >> "$f"; echo "added  $k to ${f##*/}"
  fi
  chmod 600 "$f"
}
add_env_line "$REG/env/registry.env" MIZAN3_PROVIDER_TOKEN "$PT_MIZAN3"
add_env_line "$REG/env/registry.env" ALGHADR_PROVIDER_TOKEN "$PT_ALGHADR"
add_env_line "$REG/env/registry.env" MANLA_PROVIDER_TOKEN "$PT_MANLA"
add_env_line "$GW/env/gateway.env"    MIZAN3_PROVIDER_TOKEN "$PT_MIZAN3"
add_env_line "$GW/env/gateway.env"    ALGHADR_PROVIDER_TOKEN "$PT_ALGHADR"
add_env_line "$GW/env/gateway.env"    MANLA_PROVIDER_TOKEN "$PT_MANLA"

echo "=== 4. recreate registry + gateway (NO down, NO volume removal) ==="
cd "$REG" && docker compose -f compose.registry.yml up -d
cd "$GW"  && docker compose -f compose.gateway.yml up -d
i=0; until curl -sf http://127.0.0.1:8200/health >/dev/null 2>&1; do i=$((i+1)); [ $i -ge 30 ] && fail "registry unhealthy"; sleep 1; done
i=0; until curl -sf http://127.0.0.1:8210/health >/dev/null 2>&1; do i=$((i+1)); [ $i -ge 30 ] && fail "gateway unhealthy"; sleep 1; done
echo "registry + gateway healthy"

echo "=== 5. before: enabled providers ==="
reg http://127.0.0.1:8200/api/rag-registry | python3 -c 'import json,sys; print([p["rag_id"] for p in json.load(sys.stdin)["providers"]])'

echo "=== 6. create the 3 providers ==="
mkpayload() { # rid disp base authref prio desc
  python3 - "$1" "$2" "$3" "$4" "$5" "$6" <<'PY'
import json, sys
rid, disp, base, authref, prio, desc = sys.argv[1:7]
print(json.dumps({
    "rag_id": rid, "rag_name": rid, "display_name": disp, "description": desc,
    "provider_type": "dedicated", "base_url": base,
    "api_endpoint": "/v1", "api_contract_version": "v1",
    "healthcheck_endpoint": "/health", "auth_ref": authref,
    "master_prompt_id": "", "priority": int(prio), "retrieval_weight": 1.0,
    "fallback_priority": 100, "retrieval_config": {},
    "embedding_model": "mxbai-embed-large", "vector_index": "mxbai-embed-large-v1",
    "top_k": 5, "similarity_threshold": 0.05, "timeout_ms": 60000,
    "retry_policy": {"max_retries": 1, "backoff_ms": 500},
    "enabled": True,
    "allowed_consumers": ["radio", "portal", "gateway", "pcm23-verify"],
    "allowed_users": []}, ensure_ascii=False))
PY
}
create_provider() { # rid disp base authref prio desc  (idempotent: 409 -> skip)
  local payload resp
  payload=$(mkpayload "$1" "$2" "$3" "$4" "$5" "$6")
  resp=$(curl -s -m 15 -X POST -H "$RAUTH" -H 'Content-Type: application/json' -d "$payload" http://127.0.0.1:8200/api/rag-registry)
  if printf '%s' "$resp" | grep -q '"rag_id_exists"'; then
    echo "create $1 -> exists (idempotent skip)"
  else
    printf '%s' "$resp" | grep -q '"ok":true' || { echo "create $1 FAILED: $resp"; exit 1; }
    echo "create $1 -> ok"
  fi
}
create_provider mizan3   "تفسیر المیزان (mxbai-1024)"  http://127.0.0.1:8103 env:MIZAN3_PROVIDER_TOKEN  3 "PCM-23: المیزان re-indexed on live mxbai-embed-large 1024-dim (ollama 172.20.1.53:11434)"
create_provider alghadir "الغدیر علامه امینی"           http://127.0.0.1:8104 env:ALGHADR_PROVIDER_TOKEN 4 "PCM-23: الغدیر علامه امینی — 11 approved volumes"
create_provider manla    "من لا يحضره الفقيه"           http://127.0.0.1:8105 env:MANLA_PROVIDER_TOKEN   5 "PCM-23: من لا يحضره الفقیه — 24 volumes (main+sharh)"

echo "=== 6b. PATCH timeout_ms=60000 (build-window headroom; idempotent, If-Match) ==="
patch_timeout() { # rid
  local rid=$1 cur ua tm
  cur=$(reg "http://127.0.0.1:8200/api/rag-registry/$rid")
  ua=$(printf '%s' "$cur" | python3 -c 'import json,sys; print(json.load(sys.stdin)["provider"]["updated_at"])')
  tm=$(printf '%s' "$cur" | python3 -c 'import json,sys; print(json.load(sys.stdin)["provider"]["timeout_ms"])')
  if [ "$tm" = "60000" ]; then echo "$rid timeout_ms already 60000"; return 0; fi
  curl -s -m 15 -X PATCH -H "$RAUTH" -H 'Content-Type: application/json' -H "If-Match: $ua" \
    -d '{"timeout_ms":60000}' "http://127.0.0.1:8200/api/rag-registry/$rid" | head -c 160; echo
}
patch_timeout mizan3
patch_timeout alghadir
patch_timeout manla

echo "=== 7. portal consumer: add the 3 rag ids (keep mizan+fiqh) ==="
curl -s -m 15 -X PATCH -H "$RAUTH" -H 'Content-Type: application/json' \
  -d '{"allowed_rag_ids":["mizan","fiqh","mizan3","alghadir","manla"]}' \
  http://127.0.0.1:8200/api/rag-registry/consumers/portal | head -c 400
echo

echo "=== 8. test-connection + test-auth per provider ==="
for r in mizan3 alghadir manla; do
  echo "--- $r test-connection ---"
  curl -s -m 15 -X POST -H "$RAUTH" "http://127.0.0.1:8200/api/rag-registry/$r/test-connection"; echo
  echo "--- $r test-auth ---"
  curl -s -m 15 -X POST -H "$RAUTH" "http://127.0.0.1:8200/api/rag-registry/$r/test-auth"; echo
done

echo "=== 9. temp verify consumer + gateway E2E ==="
RESP=$(curl -s -m 15 -X POST -H "$RAUTH" -H 'Content-Type: application/json' \
  -d '{"consumer_id":"pcm23-verify","display_name":"PCM-23 gateway verification","description":"temp consumer for PCM-23 acceptance","allowed_rag_ids":["mizan3","alghadir","manla"],"default_rag_id":"alghadir","routing_policy":"single"}' \
  http://127.0.0.1:8200/api/rag-registry/consumers)
CKEY=$(printf '%s' "$RESP" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("api_key",""))' 2>/dev/null || true)
if [ -z "$CKEY" ]; then
  if [ -f /tmp/pcm23-ckey ]; then CKEY=$(cat /tmp/pcm23-ckey); echo "reusing stored pcm23-verify key (create: $(printf '%s' "$RESP" | head -c 120))"
  else fail "consumer create failed: $RESP"; fi
fi
printf '%s' "$CKEY" > /tmp/pcm23-ckey
chmod 600 /tmp/pcm23-ckey
GSK=$(docker inspect rag-gateway --format '{{.Config.Env}}' | tr ' ' '\n' | grep '^GATEWAY_SERVICE_KEY=' | cut -d= -f2-)
printf '%s' "$GSK" > /tmp/pcm23-gwkey
chmod 600 /tmp/pcm23-gwkey
echo "--- gateway /v1/models (consumer pcm23-verify) ---"
curl -s -m 15 http://127.0.0.1:8210/v1/models -H "Authorization: Bearer $GSK" -H "X-Consumer-Key: $CKEY" | head -c 600; echo
echo "--- gateway chat: rag-alghadir (RAG search + LLM) ---"
# NOTE: while the index is still building, the provider's `embeddings` table
# commits only at build end (single atomic session) -> search is FTS-lexical
# only and citations may be empty / the LLM may abstain ("پاسخ نمی‌دهم").
# That is EXPECTED mid-build; once remaining:0, re-run to confirm real
# citations. A 502 here with provider_unreachable means timeout too small.
curl -s -m 180 http://127.0.0.1:8210/v1/chat/completions \
  -H "Authorization: Bearer $GSK" -H "X-Consumer-Key: $CKEY" -H 'Content-Type: application/json' \
  -d '{"model":"rag-alghadir","messages":[{"role":"user","content":"علامه امینی در کتاب الغدیر درباره غدیر خم چه می‌گوید؟"}]}' | head -c 900; echo

echo "=== 10. after: enabled providers + portal consumer record ==="
reg http://127.0.0.1:8200/api/rag-registry | python3 -c 'import json,sys; print("enabled:", [p["rag_id"] for p in json.load(sys.stdin)["providers"]])'
# NOTE: the registry's `GET /consumers/<id>/rags` route is NOT in the deployed
# rag-registry image (v0.1.0, built Nov 13) — that route exists only in the
# newer E0/E5 source tree. The portal's real listing path is the gateway
# dual filter, so we verify what the portal actually sees via gateway /v1/models
# (already shown in step 9) + the registry consumer record (list endpoint).
reg http://127.0.0.1:8200/api/rag-registry/consumers | python3 -c 'import json,sys
d=json.load(sys.stdin)
cons=d.get("consumers",d if isinstance(d,list) else [])
for c in cons:
    if c.get("consumer_id")=="portal": print("portal allowed_rag_ids:", c.get("allowed_rag_ids"))'
echo "=== REGISTER OK (TS=$TS) ==="
